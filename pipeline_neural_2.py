class FoodDatasetCascaded(Dataset):
    """Text + hazard probabilities → product category"""
    def __init__(self, texts, hazard_probs, labels=None, max_length=256):
        self.texts        = list(texts)
        self.hazard_probs = hazard_probs
        self.labels       = list(labels) if labels is not None else None
        self.max_length   = max_length

    def __len__(self):
        return len(self.texts)

    def __getitem__(self, idx):
        enc = tokenizer(
            self.texts[idx],
            max_length=self.max_length,
            padding='max_length',
            truncation=True,
            return_tensors='pt'
        )
        item = {
            'input_ids':      enc['input_ids'].squeeze(),
            'attention_mask': enc['attention_mask'].squeeze(),
            'hazard_probs':   torch.tensor(self.hazard_probs[idx], dtype=torch.float)
        }
        if self.labels is not None:
            item['label'] = torch.tensor(self.labels[idx], dtype=torch.long)
        return item


class CascadedProductModel(nn.Module):
    """DistilBERT + hazard probs → product category"""
    def __init__(self, n_hazard, n_product):
        super().__init__()
        self.bert = DistilBertModel.from_pretrained(MODEL_NAME)
        self.classifier = nn.Sequential(
            nn.Linear(768 + n_hazard, 512),
            nn.ReLU(),
            nn.Dropout(0.3),
            nn.Linear(512, n_product)
        )

    def forward(self, input_ids, attention_mask, hazard_probs):
        out     = self.bert(input_ids=input_ids, attention_mask=attention_mask)
        cls     = out.last_hidden_state[:, 0, :]        # [CLS] token
        combined = torch.cat([cls, hazard_probs], dim=1) # append hazard info
        return self.classifier(combined)

