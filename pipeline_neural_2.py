def train_model(model, train_loader, valid_loader,
                class_weights, save_path, num_epochs=4, lr=2e-5):
    """
    save_path: FIX 2 — ξεχωριστό path για κάθε μοντέλο
               'best_hazard_model.pt' ή 'best_product_model.pt'
               Πριν: και τα δύο έγραφαν 'best_model.pt' → overwrite!
    """
    optimizer   = AdamW(model.parameters(), lr=lr, weight_decay=0.01)
    total_steps = len(train_loader) * num_epochs
    scheduler   = get_linear_schedule_with_warmup(
        optimizer,
        num_warmup_steps=total_steps // 10,
        num_training_steps=total_steps
    )
    loss_fn    = torch.nn.CrossEntropyLoss(weight=class_weights)
    best_f1    = 0
    best_preds = None

    for epoch in range(num_epochs):
        # ── Training ──────────────────────────
        model.train()
        total_loss = 0

        for batch_idx, batch in enumerate(train_loader):
            input_ids      = batch['input_ids'].to(device)
            attention_mask = batch['attention_mask'].to(device)
            labels         = batch['label'].to(device)

            outputs = model(input_ids=input_ids, attention_mask=attention_mask)
            loss    = loss_fn(outputs.logits, labels)
            total_loss += loss.item()

            optimizer.zero_grad()
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
            optimizer.step()
            scheduler.step()

            if (batch_idx + 1) % 50 == 0:
                print(f"  Epoch {epoch+1} | Batch {batch_idx+1}/{len(train_loader)} "
                      f"| Loss: {total_loss/(batch_idx+1):.4f}")

        # ── Validation ────────────────────────
        model.eval()
        all_preds, all_labels = [], []

        with torch.no_grad():
            for batch in valid_loader:
                input_ids      = batch['input_ids'].to(device)
                attention_mask = batch['attention_mask'].to(device)
                outputs = model(input_ids=input_ids, attention_mask=attention_mask)
                preds   = torch.argmax(outputs.logits, dim=1)
                all_preds.extend(preds.cpu().numpy())
                if 'label' in batch:
                    all_labels.extend(batch['label'].numpy())

        epoch_f1 = f1_score(all_labels, all_preds, average='macro', zero_division=0)
        avg_loss  = total_loss / len(train_loader)
        print(f"\nEpoch {epoch+1}/{num_epochs} | Loss: {avg_loss:.4f} | Val Macro-F1: {epoch_f1:.4f}")

        if epoch_f1 > best_f1:
            best_f1    = epoch_f1
            best_preds = all_preds.copy()
            torch.save(model.state_dict(), save_path)  # FIX 2
            print(f"  ✓ New best! F1={best_f1:.4f} → saved {save_path}")
        print()

    return best_preds, best_f1


