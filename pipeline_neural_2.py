def official_score(true_hazard, pred_hazard, true_product, pred_product):
    # FIX 4: zero_division=0 αποτρέπει crash
    hazard_f1    = f1_score(true_hazard, pred_hazard,
                            average='macro', zero_division=0)
    correct_mask = [p == t for p, t in zip(pred_hazard, true_hazard)]
    true_filt    = [t for t, m in zip(true_product,  correct_mask) if m]
    pred_filt    = [p for p, m in zip(pred_product,  correct_mask) if m]

    if len(true_filt) == 0:
        product_f1 = 0.0
    else:
        product_f1 = f1_score(true_filt, pred_filt,
                              average='macro', zero_division=0)

    score = (hazard_f1 + product_f1) / 2
    return hazard_f1, product_f1, score

